export function labelFor(row,spec) {
  const groupDifference=['content_observed_difference','content_fitted_contrasts'].includes(spec.id);
  const parts=(spec.labelFields ?? []).map(field => {
    const value = row[field];
    if (value == null || value === '') return '';
    if(groupDifference && ['group_b','group_b_label'].includes(field))return '';
    if(groupDifference && ['group_a','group_a_label'].includes(field)) {
      const b=row[field==='group_a'?'group_b':'group_b_label'];
      return `${valueLabel(field,value,spec.id)} minus ${valueLabel('group_b',b,spec.id)}`;
    }
    return valueLabel(field,value,spec.id);
  }).filter(Boolean);
  if(spec.id==='funding_content_contrasts')parts.push(row.degree_target==='Masters minus research doctorate'
    ? '(Master’s connected − remaining) minus (doctorate connected − remaining)'
    : 'Connected minus remaining');
  return parts.join(' · ') || 'Record';
}

export function unitFor(row,spec) {
  return row.units || row.unit || spec.unit;
}

export function valueLabel(field,value,dataset='') {
  if (value == null) return 'Not applicable';
  const token = String(value);
  if(field==='degree_target' && token==='Masters minus research doctorate' && dataset==='institutional_count_associations')return 'Master’s / doctorate';
  if(field==='extension_years')return `${token}-year award window`;
  if(field==='funding_contrast' && token==='1_to_4_annualized_funded_application_ids_per_FY')return 'Increase from one to four funded application IDs per fiscal year';
  if(field==='period_direction')return token.replace('_minus_',' minus ');
  if(field==='contrast_direction')return ({connected_minus_no_identified_connection:'Connected minus no identified connection',outside_minus_college_connection_gap:'Outside-university connection gap minus university connection gap'})[token]??token.replaceAll('_',' ');
  if(field==='measure' && token==='paired_difference')return 'Funded minus unfunded years';
  if(['joint_role','joint_state','state'].includes(field) && Object.hasOwn(TOKENS,token))return TOKENS[token];
  if (token === '') return ['soc_unit_code','soc_code_canonical','naics_code_canonical'].includes(field) ? 'No code' : 'Not specified';
  const mapField = ({institution_selection:'institution_id',occupation:'soc_code_canonical',soc_unit_code:'soc_code_canonical',industry:'naics_code_canonical',state:'joint_state',category_visibility:'category'})[field] ?? field;
  const official = VALUE_LABELS[mapField]?.[token];
  if (official) {
    return ['institution_id','soc_code_canonical','naics_code_canonical'].includes(mapField)
      ? `${token} · ${official}` : official;
  }
  if (field === 'field_code' && FIELD_NAMES[token]) return `${token} · ${FIELD_NAMES[token]}`;
  if (['group_id','group_a','group_b'].includes(field) && token.includes('|')) {
    const [degree,code] = token.split('|');
    return `${TOKENS[degree]??degree} · ${FIELD_NAMES[code]??code}`;
  }
  if (field === 'outcome' && TOKENS[token]) return `${token} · ${TOKENS[token]}`;
  if (field === 'connection_clear') return token === '1' ? 'Identified connection' : token === '0' ? 'Remaining observations' : token;
  if (Object.hasOwn(TOKENS,token)) return TOKENS[token];
  return token.replaceAll('_',' ').replace(/^./,s=>s.toUpperCase());
}

